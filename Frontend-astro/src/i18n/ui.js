export function useTranslations(locale) {
  const dic = ui[locale] ?? ui.es
  return (clave) => dic[clave] ?? ui.es[clave] ?? clave
}

export function quitarPrefijo(ruta) {
  return ruta.replace(/^\/en(?=\/|$)/, '') || '/'
}

export function rutaLocal(locale, ruta = '/') {
  const limpia = ruta.startsWith('/') ? ruta : `/${ruta}`
  if (locale === 'es') return limpia
  return limpia === '/' ? '/en' : `/en${limpia}`
}

